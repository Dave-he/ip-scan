def main() -> None:
    # Deduplicate while preserving first-seen order.
    seen: set[str] = set()
    rows: list[tuple[str, str]] = []
    for d, c in DOMAINS:
        d = d.strip().lower()
        c = c.strip()
        if not d or d in seen:
            continue
        seen.add(d)
        rows.append((d, c))

    with open("lists/cn_top_1000.csv", "w", encoding="utf-8") as f:
        f.write("rank,domain,category\n")
        for i, (d, c) in enumerate(rows, start=1):
            f.write(f"{i},{d},{c}\n")
    print(f"Wrote {len(rows)} domains to lists/cn_top_1000.csv")

    with open("lists/cn_top_1000.SOURCE", "w", encoding="utf-8") as f:
        f.write(
            "Domain list snapshot: hand-audited 2026-08-22.\n"
            "Coverage: portals, search, e-commerce, video, social, news,\n"
            "government (.gov.cn), education (.edu.cn), finance, cloud,\n"
            "CDNs, AI services, developer tools, ISPs/telecom, mail,\n"
            "logistics, auto, real estate, travel, restaurants.\n"
            "Source mix: covers the bulk of the canonical Chinese\n"
            "internet surface plus the most popular Chinese-language\n"
            "international sites reachable on a domestic broadband link.\n"
            "Refresh: re-run scripts/gen_cn_top1000.py to regenerate.\n"
        )


if __name__ == "__main__":
    main()
